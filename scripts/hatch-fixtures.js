#!/usr/bin/env node
// Writes test-visual/matrix/hatched.js: a spread of Hatch template characters,
// already validated, for the visual matrix. Regenerate after changing the templates.
const fs = require('fs');
const path = require('path');
const H = require('../characters/hatch.js');
const { validateCharacter } = require('../characters/validate.js');
const FIXTURES = [
  { name: 'Otter', shape: 'round', size: 'medium', arms: 'two', color: '#4f9be0', accessory: 'bow' },
  { name: 'Brick', shape: 'boxy', size: 'medium', arms: 'many', color: '#5fbf9a', accessory: 'scarf' },
  { name: 'Fennec', shape: 'animal', size: 'medium', arms: 'two', color: '#e0885f', accessory: 'tuft' },
  { name: 'Jar', shape: 'object', size: 'medium', arms: 'none', color: '#8f6bd6', accessory: 'none' },
  { name: 'Pebble', shape: 'round', size: 'small', arms: 'none', color: '#e8c14a', accessory: 'none' },
  { name: 'Stretch', shape: 'animal', size: 'tall', arms: 'many', color: '#e06f8f', accessory: 'bow' },
  { name: 'Block', shape: 'boxy', size: 'small', arms: 'two', color: '#7fbf5a', accessory: 'none' },
  { name: 'Tower', shape: 'object', size: 'tall', arms: 'two', color: '#d98a4a', accessory: 'scarf' },
].map((p) => {
  const r = validateCharacter(H.templateCharacter(p), { source: 'import' });
  if (!r.ok) throw new Error(`${p.name}: ${JSON.stringify(r.errors)}`);
  return r.character;
});
const out = `// Generated by scripts/hatch-fixtures.js: Hatch template characters for the matrix, registered the way an installed character is.\n(function () {\n  const C = window.BuddyCharacters;\n  const fixtures = ${JSON.stringify(FIXTURES)};\n  for (const f of fixtures) C.register(f);\n  window.HATCHED_IDS = fixtures.map((f) => f.id);\n})();\n`;
fs.writeFileSync(path.join(__dirname, '..', 'test-visual', 'matrix', 'hatched.js'), out);
console.log(FIXTURES.map((f) => f.id).join(' '));
