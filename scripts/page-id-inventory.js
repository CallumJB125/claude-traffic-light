#!/usr/bin/env node
'use strict';
// The page-id inventory (plan-redesign §R2.5 "Page-id inventory", lead
// decision 4): every place the app or its tests name a main-window page id,
// so R6 and R6b can empty it of retired ids. It is a parser of known call
// shapes, not a grep: only these count, with a single- or double-quoted
// literal argument:
//   openBuddy('…')   navigate('…')   select('…')   data-page="…"
// plus the PAGES and SECTIONS literals themselves (read by require, not text).
// Scope: the desktop app and its tests (main.js, src/, buddy-window/, the
// root pages, test/, test-visual/). The board web app, site and remote are
// separate apps with their own routes.
//
//   node scripts/page-id-inventory.js           print the inventory
//   node scripts/page-id-inventory.js --write   write test/page-id-inventory.txt
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'test', 'page-id-inventory.txt');
const SHAPES = [
  ['openBuddy', /\bopenBuddy\(\s*(['"])([^'"\\\n]+)\1\s*\)/g],
  ['navigate', /\bnavigate\(\s*(['"])([^'"\\\n]+)\1\s*\)/g],
  ['select', /\bselect\(\s*(['"])([^'"\\\n]+)\1\s*\)/g],
  ['data-page', /\bdata-page=(['"])([^'"\\\n]+)\1/g],
];
const IN_SCOPE = (f) => /\.(c?m?js|html)$/.test(f)
  && (/^(main\.js|[^/]+\.(js|html))$/.test(f) || /^(src|buddy-window|test|test-visual)\//.test(f))
  && !/(^|\/)(node_modules|__screenshots__|fixtures)\//.test(f)
  && f !== 'test/page-id-inventory.txt' && f !== 'scripts/page-id-inventory.js';

function files() {
  return execFileSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean).filter(IN_SCOPE).sort();
}

function inventory() {
  const P = require(path.join(ROOT, 'buddy-window', 'pages.js'));
  const lines = [];
  for (const p of P.flat()) lines.push(`${p.id}\tbuddy-window/pages.js\tPAGES\t1`);
  for (const s of P.SECTIONS) lines.push(`${P.sectionAddress(s)}\tbuddy-window/pages.js\tSECTIONS\t1`);
  for (const f of files()) {
    let text;
    try { text = fs.readFileSync(path.join(ROOT, f), 'utf8'); } catch { continue; }
    // Counted per file, not by line, so an edit elsewhere in a file doesn't churn the inventory.
    const counts = new Map();
    for (const [shape, re] of SHAPES) {
      re.lastIndex = 0;
      for (let m; (m = re.exec(text));) { const k = `${m[2]}\t${f}\t${shape}`; counts.set(k, (counts.get(k) ?? 0) + 1); }
    }
    for (const [k, n] of counts) lines.push(`${k}\t${n}`);
  }
  return [...new Set(lines)].sort();
}

const render = () => `# Page-id inventory: generated by scripts/page-id-inventory.js; do not edit.\n# id<TAB>file<TAB>shape<TAB>count\n${inventory().join('\n')}\n`;

if (require.main === module) {
  if (process.argv.includes('--write')) fs.writeFileSync(OUT, render());
  else process.stdout.write(render());
}

module.exports = { inventory, render, OUT, IN_SCOPE };
