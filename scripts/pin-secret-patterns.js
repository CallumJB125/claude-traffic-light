#!/usr/bin/env node
// Pins src/secret-patterns.js (the CommonJS mirror src/scrub.js uses until
// board/shared/secret-patterns.mjs is on main) and its positive-table fixture
// to one commit of the shared module:
//
//   node scripts/pin-secret-patterns.js <commit> [repo]
//
// repo defaults to ../ctl-secret-patterns (buddy-builder-4's worktree). Both
// files are read with `git show <commit>:…`, never from a working copy, and
// both are stamped with the commit.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const commit = process.argv[2];
const repo = process.argv[3] || path.join(ROOT, '..', 'ctl-secret-patterns');
if (!commit || !/^[0-9a-f]{7,40}$/.test(commit)) {
  console.error('usage: node scripts/pin-secret-patterns.js <commit> [repo]');
  process.exit(2);
}
const show = (file) => execFileSync('git', ['-C', repo, 'show', `${commit}:${file}`], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });

// ── the module ──
const src = show('board/shared/secret-patterns.mjs');
const lines = src.split('\n');
const start = lines.findIndex((l) => l && !l.startsWith('//'));
const body = lines.slice(start).join('\n').replace(/^export (const|function) /gm, '$1 ');
if (/^\s*export\b/m.test(body) || /^\s*import\b/m.test(body)) throw new Error('the module has an export/import form this script does not convert');
const names = [...src.matchAll(/^export (?:const|function) (\w+)/gm)].map((m) => m[1]);
const header = `// A CommonJS mirror of board/shared/secret-patterns.mjs at feat/secret-patterns
// ${commit} (buddy-builder-4), generated by scripts/pin-secret-patterns.js
// (\`export\` dropped, module.exports added). That module is still in review;
// once it is on main, src/scrub.js requires it instead (a one-line change
// there) and this file is deleted. Don't edit it: re-pin.
`;
const out = path.join(ROOT, 'src', 'secret-patterns.js');
fs.writeFileSync(out, `${header}\n${body.trimEnd()}\n\nmodule.exports = { ${names.join(', ')} };\n`);
delete require.cache[require.resolve(out)];
const Shared = require(out);

// ── the positive table ──
const t = show('test/secret-patterns.test.js');
const helpers = t.slice(t.indexOf('const j = '), t.indexOf('const secretOf'));
const from = t.indexOf('const POSITIVES = [');
const table = t.slice(from, t.indexOf('\n];', from) + 3);
// eslint-disable-next-line no-new-func
const POSITIVES = new Function(`${helpers}\n${table}\nreturn POSITIVES;`)();
// Every string is stored as 3-character fragments: no secret shape fits in
// three characters, so no scanner (GitHub push protection decodes base64
// too) sees a token in the repo. The test joins them back.
const parts = (s) => s.match(/[\s\S]{1,3}/g) || [];
const rows = POSITIVES.map(([kind, text, span]) => {
  const hit = Shared.findSecrets(text)[0];
  const secret = span || (hit && text.slice(hit.index, hit.index + hit.length));
  if (!secret) throw new Error(`${kind}: the module at ${commit} finds nothing in its own positive ${JSON.stringify(text)}`);
  return { kind, text: parts(text), secret: parts(secret) };
});
fs.writeFileSync(path.join(ROOT, 'test', 'fixtures', 'secret-patterns-positives.json'), `${JSON.stringify({
  commit,
  source: `feat/secret-patterns ${commit}: test/secret-patterns.test.js POSITIVES (the span each row names, or the module's first hit at that commit). Regenerate with node scripts/pin-secret-patterns.js <commit>.`,
  encoding: 'text and secret are arrays of 3-character fragments (join with \'\'), so the repo never holds a string a secret scanner or push protection would flag',
  rows,
}, null, 1)}\n`);
console.log(`pinned ${commit}: ${Shared.SECRET_PATTERNS.length} kinds, ${rows.length} positives`);
