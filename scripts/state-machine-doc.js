#!/usr/bin/env node
// Writes docs/state-machine.md from hooks/session-machine.js, so the diagram
// can't drift from the code (test/session-machine.test.js checks it).
//
//   node scripts/state-machine-doc.js
const fs = require('fs');
const path = require('path');
const M = require('../hooks/session-machine.js');

const OUT = path.join(__dirname, '..', 'docs', 'state-machine.md');

function matrix(writer) {
  const cells = new Map(M.table(writer).map((t) => [`${t.from}|${t.event}`, t]));
  const rows = [`| from \\ event | ${M.EVENTS.join(' | ')} |`, `|---|${M.EVENTS.map(() => '---').join('|')}|`];
  for (const from of M.STATES) {
    const row = M.EVENTS.map((event) => {
      const t = cells.get(`${from}|${event}`);
      const to = t.to || M.stateOf({ signal: M.EVENT_SIGNAL[event] });
      return t.rule === 'signal' || t.rule === 'end' ? to : `**${to}**¹`;
    });
    rows.push(`| **${from}** | ${row.join(' | ')} |`);
  }
  return rows.join('\n');
}

function render() {
  const eventRows = M.EVENTS.map((e) => {
    const sigs = Object.keys(M.EVENT_OF_SIGNAL).filter((s) => M.EVENT_OF_SIGNAL[s] === e);
    if (e === 'agent') sigs.push('tool-* or permission-denied carrying an agent_id');
    return `| \`${e}\` | ${sigs.map((s) => (s.includes(' ') ? s : `\`${s}\``)).join(', ')} |`;
  });
  const stateRows = M.STATES.map((s) => {
    const sigs = s === 'absent' ? 'no session file' : s === 'working' ? 'any signal that does not end the turn' : [...M.TURN_END].filter((sig) => M.stateOf({ signal: sig }) === s).map((x) => `\`${x}\``).join(', ');
    return `| \`${s}\` | ${sigs} |`;
  });
  const ruleRows = M.TRANSITIONS.map((t) => `| \`${t.id}\` | ${t.from === '*' ? 'any' : t.from.join(', ')} | ${t.on === '*' ? 'any' : `\`${t.on}\``} | ${t.to}${t.bookkeeping ? ' (bookkeeping)' : ''} | ${t.hooksOnly ? 'hook only' : 'all'} | ${t.why} |`);
  const presentRows = M.PRESENTATION.map((p, i) => `| ${i + 1} | \`${p.id}\` | ${p.shows} | ${p.why} |`);
  return `# Session state machine

<!-- Generated by scripts/state-machine-doc.js from hooks/session-machine.js. Do not edit by hand. -->

Every Claude Code session (and every other agent reporting through \`emit.js\`
or the app's \`/signal\` endpoint) is a session file whose stored signal puts it
in one state of a small machine. The **writer** side — which signal a hook
leaves on the file — is \`step()\`; the **reader** side — what the widget shows
for a stored session right now — is \`classify()\`. Both live in
\`hooks/session-machine.js\`, are pure, and are what \`set-status.js\`,
\`session-state.js\` (bare signals), \`main.js\` and \`mcp-server.js\` call.

## States

| state | stored signal |
|---|---|
${stateRows.join('\n')}

Every state but \`absent\` and \`working\` has closed the turn (\`TURN_END\`):
the working-since clock stops there.

## Events

| event | resolved hook signals |
|---|---|
${eventRows.join('\n')}

A Notification is resolved first: \`permission_prompt\` / elicitation →
\`permission-ask\`, \`idle_prompt\` → \`idle-nudge\`, usage-limit text →
\`limit-hit\`; a PermissionRequest and an AskUserQuestion tool use are
\`permission-ask\` too. A SessionStart after a compaction (\`source: compact\`)
is \`compact\`: the session is carrying on, not freshly opened.

## Transition rules

First matching rule wins.

| rule | from | on | to | writer | why |
|---|---|---|---|---|---|
${ruleRows.join('\n')}

\`keep\` leaves the stored signal (and its tool, ask kind, via and failure)
as it was. **Bookkeeping** rows update agent and task lists but must not look
like the session moved: \`updatedAt\` holds, \`agentsAt\` is stamped, and a
closed turn keeps its \`workingSince\`. A bare signal (\`emit.js\`, \`/signal\`)
goes through the same guards; it carries no \`agent_id\`, so only its
\`subagent-*\` signals are agent events. Hook-only rows need data only the
hook has (task counting), so a bare writer skips them.

## Transition table (Claude Code hooks)

Target state for every (state, event) pair. **Bold¹** marks a guarded
\`keep\`: the event did not change what the session shows.

${matrix('hook')}

Bare signals (\`emit.js\`, \`/signal\`) differ only where a hook-only row
would have applied:

${matrix('bare')}

## Diagram

\`\`\`mermaid
${M.mermaid()}
\`\`\`

## Reading a session (what the widget shows)

\`classify()\` runs on every stored session at every poll. The first row that
applies decides; only \`held\`, \`promoted\` and \`shown\` put the session in
front of the rules engine.

| # | outcome | shows | when |
|---|---|---|---|
${presentRows.join('\n')}

\`\`\`mermaid
stateDiagram-v2
  [*] --> stored
  stored --> dropped: no-signal / gone
  stored --> held: young notification ask
  stored --> promoted: ${[...M.PROMOTABLE_TURN_END].join(' / ')} + working agent
  stored --> shown: otherwise
  held --> shown: after ${M.TRANSIENT_ASK_MS} ms, or a pending request
  promoted --> dropped: stale-agents
  held --> dropped: stale
  shown --> dropped: stale
\`\`\`

Stale windows: \`workingStaleMinutes\` for a working signal,
\`waitingStaleHours\` for a waiting-on-you one (${[...M.WAITING_ON_YOU].map((s) => `\`${s}\``).join(', ')})
or a quiet one (${[...M.QUIET].map((s) => `\`${s}\``).join(', ')}: open, no prompt yet);
a promoted session lives while any working agent is younger than
${M.AGENT_KEEPALIVE_MS / 3600000} h or anything moved within the working window.
`;
}

module.exports = { render, OUT };

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, render());
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
