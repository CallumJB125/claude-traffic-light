'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('sessionsApi', {
  state: () => ipcRenderer.invoke('sessions:state'),
  aiTools: () => ipcRenderer.invoke('sessions:aitools'),
  handover: (action, key) => ipcRenderer.invoke('sessions:handover', action, key),
  timeline: key => ipcRenderer.invoke('timeline:open', key),
  setup: () => ipcRenderer.invoke('sessions:setup'),
  pickFolder: () => ipcRenderer.invoke('sessions:pick-folder'),
  linkRepo: (folder, board) => ipcRenderer.invoke('sessions:link-repo', { folder, board }),
  linkFromSession: (handle) => ipcRenderer.invoke('sessions:link-from-session', handle),
  start: (folder, ai, prompt) => ipcRenderer.invoke('sessions:start', { folder, ai, prompt }),
  makeCard: (handle, board) => ipcRenderer.invoke('sessions:make-card', handle, board),
  searchCards: (query) => ipcRenderer.invoke('sessions:search-cards', query),
  attach: (handle, ref) => ipcRenderer.invoke('sessions:attach', handle, ref),
  share: (handle, on) => ipcRenderer.invoke('sessions:share', handle, on),
  connect: () => ipcRenderer.invoke('sessions:connect'),
  burstShare: (repo, on) => ipcRenderer.invoke('burst:handover-share', repo, on),
  burstView: (name, args) => ipcRenderer.invoke('burst:view', name, args),
  burstAction: (id, args) => ipcRenderer.invoke('burst-action', id, args),
  contextBreakdown: (session) => ipcRenderer.invoke('burst:context-breakdown', session),
  messageOwned: (session, text) => ipcRenderer.invoke('sessions:message', session, text),
  openRecord: (recordId) => ipcRenderer.invoke('sessions:open-record', recordId),
  continueMenu: () => ipcRenderer.invoke('continue:menu'),
  continueIn: (key, to) => ipcRenderer.invoke('continue:run', String(key), String(to)),
  continueHandoff: (key, to) => ipcRenderer.invoke('continue:handoff', String(key), String(to)),
  continueReply: (id, text) => ipcRenderer.invoke('continue:reply', String(id), String(text)),
  continueEnd: (id) => ipcRenderer.invoke('continue:end', String(id)),
  onContinue: (cb) => ipcRenderer.on('continue:event', (_e, ev) => cb(ev)),
  // Agent mail (src/agent-mail.js): main resolves every id against the hub again.
  mailList: () => ipcRenderer.invoke('mail:list'),
  openAccount: () => ipcRenderer.invoke('sessions:open-account'),
  mailRelease: (id, decision, digest, body) => ipcRenderer.invoke('mail:release', String(id), String(decision), String(digest), typeof body === 'string' ? body : undefined),
  mailOpen: (id) => ipcRenderer.invoke('mail:open', String(id)),
  mailAnswer: (id, text) => ipcRenderer.invoke('mail:answer', String(id), String(text)),
  mailDecline: (id, reason) => ipcRenderer.invoke('mail:decline', String(id), String(reason || '')),
  mailAskAi: (id, to) => ipcRenderer.invoke('mail:ask-ai', String(id), String(to)),
  mailPickFolder: () => ipcRenderer.invoke('mail:pick-folder'),
  mailAccept: (id, folder, ai) => ipcRenderer.invoke('mail:accept', String(id), String(folder), String(ai)),
  onMail: (cb) => ipcRenderer.on('mail:changed', () => cb()),
  // A hand-off the person starts to a teammate (same packet preview as a tool hand-off; sent through the team hub).
  mailTeammates: (key) => ipcRenderer.invoke('mail:teammates', String(key)),
  mailHandoff: (key, to) => ipcRenderer.invoke('mail:handoff', String(key), String(to)),
  // Hand-off requests from a running AI (src/handoff-requests.js): the person confirms, dismisses, or reads the outcome.
  handoffRequests: () => ipcRenderer.invoke('handoff:list'),
  handoffConfirm: (id) => ipcRenderer.invoke('handoff:confirm', String(id)),
  handoffDismiss: (id) => ipcRenderer.invoke('handoff:dismiss', String(id)),
  onHandoffRequests: (cb) => ipcRenderer.on('handoff:changed', () => cb()),
});
