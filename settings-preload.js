const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('settingsApi', {
  getConfig: () => ipcRenderer.invoke('get-config'),
  // main answers a failed save with {error}; surface it as a rejection so no caller stores it as the config
  saveConfig: async (partial) => {
    const r = await ipcRenderer.invoke('save-config', partial);
    if (r && r.error) throw new Error(r.error);
    return r;
  },
  connectAgent: (which) => ipcRenderer.invoke('connect-agent', which),
  signalEndpoint: () => ipcRenderer.invoke('signal-endpoint'),
  cliStatus: () => ipcRenderer.invoke('cli-install-status'),
  cliInstall: () => ipcRenderer.invoke('cli-install'),
  nativeBoardStatus: () => ipcRenderer.invoke('native-board-status'),
  nativeBoardBoards: (workspace) => ipcRenderer.invoke('native-board-boards', workspace),
  nativeBoardConnect: (input) => ipcRenderer.invoke('native-board-connect', input),
  nativeBoardDisconnect: (target) => ipcRenderer.invoke('native-board-disconnect', target),
  gitStatus: () => ipcRenderer.invoke('git-status'),
  deploySettings: () => ipcRenderer.invoke('deploy:settings'),
  deploySetEnabled: (on) => ipcRenderer.invoke('deploy:set-enabled', on === true),
  deployTokenSave: (provider, token) => ipcRenderer.invoke('deploy:token-save', String(provider), typeof token === 'string' ? token.slice(0, 400) : ''),
  deployTokenRemove: (provider) => ipcRenderer.invoke('deploy:token-remove', String(provider)),
  spend: () => ipcRenderer.invoke('get-spend'),
  busyStatus: () => ipcRenderer.invoke('busy-status'),
  busyOpenPrivacy: () => ipcRenderer.invoke('busy-open-privacy'),
  busyReconnectCalendar: () => ipcRenderer.invoke('busy-reconnect-calendar'),
  voiceStatus: () => ipcRenderer.invoke('voice-status'),
  compactionStats: () => ipcRenderer.invoke('compaction-stats'),
  privacyText: () => ipcRenderer.invoke('get-privacy'),
  exportStats: (format, days) => ipcRenderer.invoke('export-stats', format, days),
  exportSetup: () => ipcRenderer.invoke('setup-export'),
  showDataFolder: () => ipcRenderer.invoke('show-data-folder'),
  crashReportsState: () => ipcRenderer.invoke('crash-reports:state'),
  crashReportsSetOptIn: (on) => ipcRenderer.invoke('crash-reports:set-opt-in', on),
  crashReportsExport: () => ipcRenderer.invoke('crash-reports:export'),
  policyState: () => ipcRenderer.invoke('policy:state'),
  policyPreview: (req) => ipcRenderer.invoke('policy:preview', req),
  policyApply: (req) => ipcRenderer.invoke('policy:apply', req),
  policyPickFolder: () => ipcRenderer.invoke('policy:pick-folder'),
  dataInventory: () => ipcRenderer.invoke('data:inventory'),
  dataExport: () => ipcRenderer.invoke('data:export'),
  dataExportActivity: () => ipcRenderer.invoke('data:export-activity'),
  dataDelete: (req) => ipcRenderer.invoke('data:delete', req),
  remoteDevices: () => ipcRenderer.invoke('remote-devices'),
  remotePair: (name) => ipcRenderer.invoke('remote-pair', name),
  remoteRevoke: (id) => ipcRenderer.invoke('remote-revoke', id),
  remoteCopyCode: (code) => ipcRenderer.invoke('remote-copy-code', code),
  interactionHostStatus: () => ipcRenderer.invoke('interaction-host-status'),
  health: () => ipcRenderer.invoke('health-report'),
  healthFix: (id) => ipcRenderer.invoke('health-fix', id),
  copyDiagnostics: () => ipcRenderer.invoke('health-copy-diagnostics'),
  backupsList: () => ipcRenderer.invoke('backups-list'),
  backupsNow: () => ipcRenderer.invoke('backups-now'),
  backupsDiff: (id) => ipcRenderer.invoke('backups-diff', id),
  backupsRestore: (id, pick) => ipcRenderer.invoke('backups-restore', id, pick),
  backupsOpenFolder: () => ipcRenderer.invoke('backups-open-folder'),
  accountView: () => ipcRenderer.invoke('account-view'),
  accountOpen: (which) => ipcRenderer.invoke('account-open', which),
  onAccountChanged: (cb) => ipcRenderer.on('account-changed', () => cb()),
  burstStatus: () => ipcRenderer.invoke('burst:status'),
  burstConsent: (kind, mode) => ipcRenderer.invoke('burst:consent-text', kind, mode),
  burstAction: (req) => ipcRenderer.invoke('burst:action', req),
  burstTest: () => ipcRenderer.invoke('burst:test'),
  burstSetCompaction: (req) => ipcRenderer.invoke('burst:set-compaction', req),
  openFeedback: () => ipcRenderer.invoke('open-feedback'),
  onShowSection: (cb) => ipcRenderer.on('show-section', (e, id) => cb(id)),
});
